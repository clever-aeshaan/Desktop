import math

num = float(input("Enter a number: "))
cos_val = math.cos(num)
sin_val = math.sin(num)
tan_val = math.tan(num)
sinh_val = math.sinh(num)
cosh_val = math.cosh(num)

print("The cos of", num, "is:", cos_val)
print("The sinh of", num, "is:", sinh_val)
print("The tan of", num, "is:", tan_val)
print("The cosh of", num, "is:", cosh_val)
print("The sin of", num, "is:", sin_val)
